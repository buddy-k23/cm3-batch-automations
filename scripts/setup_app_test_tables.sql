-- Valdo on-prem test schema setup (idempotent)
-- Run as SYSTEM (or a user with privileges to create objects in APP_INT/APP_AUDIT)
-- Example:
--   sqlplus system/<password>@localhost:1521/FREEPDB1 @scripts/setup_app_test_tables.sql -- gitleaks:allow

WHENEVER SQLERROR EXIT SQL.SQLCODE

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE APP_INT."TRANSACTION" CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE APP_INT.CUSTOMER CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE APP_AUDIT.APP_LOAD_AUDIT CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

PROMPT Creating CUSTOMER table in APP_INT...
CREATE TABLE APP_INT.CUSTOMER (
  CUSTOMER_ID      VARCHAR2(20) PRIMARY KEY,
  FIRST_NAME       VARCHAR2(50)  NOT NULL,
  LAST_NAME        VARCHAR2(50)  NOT NULL,
  EMAIL            VARCHAR2(100),
  PHONE_NUMBER     VARCHAR2(20),
  ACCOUNT_BALANCE  NUMBER(12,2)  DEFAULT 0 NOT NULL,
  STATUS           VARCHAR2(20)  NOT NULL,
  CREATED_TS       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP
);

PROMPT Creating TRANSACTION table in APP_INT...
CREATE TABLE APP_INT."TRANSACTION" (
  TRANSACTION_ID    VARCHAR2(20) PRIMARY KEY,
  CUSTOMER_ID       VARCHAR2(20) NOT NULL,
  TRANSACTION_DATE  DATE         NOT NULL,
  AMOUNT            NUMBER(12,2) NOT NULL,
  TRANSACTION_TYPE  VARCHAR2(20) NOT NULL,
  DESCRIPTION       VARCHAR2(200),
  CREATED_TS        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_TRX_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
    REFERENCES APP_INT.CUSTOMER (CUSTOMER_ID)
);

PROMPT Creating Valdo load audit table in APP_AUDIT...
CREATE TABLE APP_AUDIT.APP_LOAD_AUDIT (
  AUDIT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  LOAD_TS          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PIPELINE_NAME    VARCHAR2(100) NOT NULL,
  STATUS           VARCHAR2(20)  NOT NULL,
  RECORD_COUNT     NUMBER,
  DETAILS          VARCHAR2(400)
);

COMMIT;
PROMPT Done.
