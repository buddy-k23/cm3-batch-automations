@dataclass(frozen=True)
class RulesRow:
    """One rule row from a ``*_Rules`` sheet.

    The column set matches the existing
    ``src/config/ba_rules_template_converter.BARulesTemplateConverter`` so
    EC-S5 can re-use the same downstream converter without adapter code.

    Every value is preserved as the raw cell string (or ``None`` if blank).
    EC-S5 handles rule-type mapping, value parsing, and severity coercion
    in one place.

    Attributes:
        rule_id: Stable rule identifier (``R001``, ``R002``).
        rule_name: Human-readable rule name; ``None`` if blank.
        field: DASH-style field name the rule applies to. For cross-row
            rules this may carry the ``KEY>TARGET`` or ``FIELD1|FIELD2``
            syntax — preserved verbatim and parsed downstream.
        rule_type: BA-friendly rule type token (``not_empty``, ``numeric``,
            ``exact_length``, ``valid_values``, ``cross_row:unique``,
            ``cross_field``, ``allowed values``, ``range``, ``length``,
            ``regex``, ``date format``).
        severity: ``error``, ``warning``, etc.; ``None`` if blank.
        enabled: ``Y``/``Yes``/``True``/``1`` truthy; ``None`` if blank.
            Coerced to bool by EC-S5.
        message: Free-text user-facing message; ``None`` if blank.
        expected_values: Pipe- or comma-separated values, or
            ``min..max`` ranges, or regex patterns, or date-format codes.
            Interpretation depends on ``rule_type``; ``None`` if blank.
        condition: Optional condition expression (the legacy
            ``Condition (optional)`` column); ``None`` if blank.
        notes: Optional notes column; ``None`` if blank.
    """

    rule_id: str
    rule_name: str | None
    field: str
    rule_type: str
    severity: str | None
    enabled: str | None
    message: str | None
    expected_values: str | None
    condition: str | None
    notes: str | None


