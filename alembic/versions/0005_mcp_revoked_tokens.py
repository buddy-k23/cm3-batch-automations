    """Drop MCP_REVOKED_TOKENS and its index."""
    if not _table_exists("MCP_REVOKED_TOKENS"):
        return
    op.drop_index("IDX_MCP_REVOKED_AT", table_name="MCP_REVOKED_TOKENS")
